// Generates prisma/schema.prisma from prisma/schema.template.prisma.
// Local development uses SQLite (DATABASE_URL="file:./dev.db"); Hostinger uses MySQL.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");

for (const file of [".env.local", ".env"]) {
  const p = path.join(root, file);
  if (existsSync(p)) process.loadEnvFile(p);
}

const url = process.env.DATABASE_URL ?? "";
let provider;
if (url.startsWith("file:")) provider = "sqlite";
else if (url.startsWith("mysql://")) provider = "mysql";
else {
  console.error(
    'DATABASE_URL must start with "file:" (SQLite, local) or "mysql://" (MySQL, production).'
  );
  process.exit(1);
}

const template = readFileSync(path.join(root, "prisma/schema.template.prisma"), "utf8");
const schema =
  "// GENERATED by scripts/prepare-schema.mjs — edit schema.template.prisma instead.\n" +
  template
    .replaceAll("{{PROVIDER}}", provider)
    .replaceAll("{{TEXT}}", provider === "mysql" ? "@db.Text" : "");

writeFileSync(path.join(root, "prisma/schema.prisma"), schema);
console.log(`prisma/schema.prisma generated for ${provider}`);
